export function installContextHelp(){
 const dialog=document.getElementById('helpDialog'),title=document.getElementById('helpTitle'),content=document.getElementById('helpContent');
 for(const b of document.querySelectorAll('[data-help]'))b.onclick=e=>{e?.preventDefault();e?.stopPropagation();const topic=helpTopics[b.dataset.help];if(!topic)return;title.textContent=topic.title;content.replaceChildren();for(const text of topic.paragraphs){const p=document.createElement('p');p.textContent=text;content.append(p);}dialog.showModal();};
}
